import { NextResponse } from "next/server"
import { z } from "zod"
import { requireAuth } from "@/lib/auth/guard"
import { db } from "@/lib/data/mock-db"
import bcrypt from "bcryptjs"

const generateCredsSchema = z.object({
  targetType: z.enum(["teacher", "student"]),
  targetId: z.string().min(1, "Target entity ID is required"),
  assignedClasses: z.string().optional(),
})

export async function POST(request: Request) {
  try {
    const session = await requireAuth()
    const body = await request.json()
    const parsed = generateCredsSchema.safeParse(body)

    if (!parsed.success) {
      return NextResponse.json(
        {
          success: false,
          error: {
            code: "VALIDATION_ERROR",
            message: "Invalid credential generation request",
            details: parsed.error.format(),
          },
        },
        { status: 400 }
      )
    }

    const { targetType, targetId, assignedClasses } = parsed.data

    // Authority rules
    if (targetType === "teacher") {
      // Only Principal / Super Admin can generate credentials for teachers
      if (session.role !== "principal" && session.role !== "super_admin") {
        return NextResponse.json(
          { success: false, error: { message: "Only Principals and Super Admins can generate teacher credentials." } },
          { status: 403 }
        )
      }

      const teacher = db.users.getById(targetId)
      if (!teacher) {
        return NextResponse.json({ success: false, error: { message: "Teacher record not found" } }, { status: 404 })
      }

      const cleanLastName = (teacher.lastName || teacher.firstName || "FACULTY").toUpperCase().replace(/[^A-Z]/g, "")
      const generatedUsername = `TCH-${cleanLastName.slice(0, 5)}${Math.floor(10 + Math.random() * 89)}`
      const tempPassword = `Sarbix@${Math.floor(1000 + Math.random() * 9000)}`
      const passwordHash = await bcrypt.hash(tempPassword, 10)

      teacher.passwordHash = passwordHash

      db.audit.log({
        userId: session.userId,
        userEmail: session.email,
        userRole: session.role,
        campusId: session.campusId,
        action: "UPDATE",
        resource: "user_credentials",
        resourceId: teacher.id,
        details: { targetRole: "teacher", username: generatedUsername, assignedClasses },
        ipAddress: "127.0.0.1",
      })

      return NextResponse.json({
        success: true,
        message: "Teacher credentials generated successfully",
        credentials: {
          userId: teacher.id,
          username: generatedUsername,
          email: teacher.email,
          tempPassword,
          role: "teacher",
          assignedToName: `${teacher.firstName} ${teacher.lastName}`,
          assignedClasses: assignedClasses || "Assigned by Management",
        },
      })
    } else {
      // Student credentials: Can be generated by Principal, Super Admin, OR Teacher
      if (session.role !== "teacher" && session.role !== "principal" && session.role !== "super_admin") {
        return NextResponse.json(
          { success: false, error: { message: "Unauthorized: Only Teachers and Principals can issue student credentials." } },
          { status: 403 }
        )
      }

      const student = db.students.getById(targetId)
      if (!student) {
        return NextResponse.json({ success: false, error: { message: "Student record not found" } }, { status: 404 })
      }

      const cleanFirstName = student.firstName.toUpperCase().replace(/[^A-Z]/g, "")
      const rollSuffix = (student.rollNumber || "01").replace(/[^0-9]/g, "").slice(-2) || "14"
      const generatedUsername = `STU-${cleanFirstName.slice(0, 5)}${rollSuffix}`
      const tempPassword = `Student@${Math.floor(1000 + Math.random() * 9000)}`
      const passwordHash = await bcrypt.hash(tempPassword, 10)

      // Ensure user entry exists or update password
      const existingUser = db.users.getByEmail(`${generatedUsername.toLowerCase()}@delhi.sarbix.edu`)
      if (existingUser) {
        existingUser.passwordHash = passwordHash
      } else {
        db.users.create({
          id: `usr-${targetId}`,
          email: `${generatedUsername.toLowerCase()}@delhi.sarbix.edu`,
          firstName: student.firstName,
          lastName: student.lastName,
          role: "student",
          campusId: student.campusId,
          passwordHash,
          isActive: true,
        })
      }

      db.audit.log({
        userId: session.userId,
        userEmail: session.email,
        userRole: session.role,
        campusId: session.campusId,
        action: "UPDATE",
        resource: "student_credentials",
        resourceId: student.id,
        details: { targetRole: "student", username: generatedUsername, studentName: `${student.firstName} ${student.lastName}` },
        ipAddress: "127.0.0.1",
      })

      return NextResponse.json({
        success: true,
        message: `Student Desk credentials generated for ${student.firstName} ${student.lastName}`,
        credentials: {
          userId: student.id,
          username: generatedUsername,
          email: `${generatedUsername.toLowerCase()}@delhi.sarbix.edu`,
          tempPassword,
          role: "student",
          assignedToName: `${student.firstName} ${student.lastName}`,
          assignedClasses: `${student.classGrade} - ${student.section}`,
        },
      })
    }
  } catch (error: any) {
    return NextResponse.json(
      { success: false, error: { message: error.message || "Failed to generate credentials" } },
      { status: error.status || 500 }
    )
  }
}

